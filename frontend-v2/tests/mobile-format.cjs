const assert = require('node:assert/strict')
const vm = require('node:vm')
const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')
const context = { exports: {}, URL, URLSearchParams }
const source = fs.readFileSync(path.join(__dirname, '../src/mobile/format.ts'), 'utf8')
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, context)
const f = context.exports
assert.equal(f.shortCode('Z.001.000227'), '227')
assert.equal(f.shortCode('000205'), '205')
assert.equal(f.shortCode(null), '—')
assert.equal(f.shortLocation('EDIT-028·左侧第1位'), 'E28 左1')
assert.equal(f.shortLocation('EDIT-028·右侧第6位'), 'E28 右6')
assert.equal(f.compactText('产品 Z.001.000227'), '产品 227')
assert.equal(f.quantity(null), '—')
assert.equal(f.quantity(0), '0')
assert.equal(f.money('bad'), '—')
assert.equal(f.mobileQrRoute('https://evil.example/q/101', 'http://localhost:18748', 'http://localhost:8002'), null)
assert.equal(f.mobileQrRoute('javascript:alert(1)', 'http://localhost:18748', 'http://localhost:8002'), null)
assert.equal(f.mobileQrRoute('http://name:secret@localhost/q/101', 'http://localhost:18748', 'http://localhost:8002'), null)
assert.equal(f.mobileQrRoute('http://localhost:8002/q/101', 'http://localhost:18748', 'http://localhost:8002'), '/q/101')
assert.equal(f.mobileQrRoute('/M/12', 'http://localhost:18748', 'http://localhost:8002'), '/M/12')
assert.equal(f.mobileQrRoute('/P/7', 'http://localhost:18748', 'http://localhost:8002'), '/P/7')
assert.equal(f.mobileQrRoute('/I/70', 'http://localhost:18748', 'http://localhost:8002'), '/I/70')
assert.equal(f.mobileQrRoute('/sp/1/2/3/4', 'http://localhost:18748', 'http://localhost:8002'), '/sp/1/2/3/4')
assert.equal(f.mobileQrRoute('/warehouse.html?floor=3F&rack_id=EDIT-028', 'http://localhost:18748', 'http://localhost:8002'), '/scan/rack?floor=3F&rack_id=EDIT-028')
assert.equal(f.mobileQrRoute('/q/101/0123456789abcdef01234567', 'http://localhost:18748', 'http://localhost:8002'), '/q/101/0123456789abcdef01234567')
assert.equal(f.mobileQrRoute('/M/12?production_task_id=8', 'http://localhost:18748', 'http://localhost:8002'), '/M/12?production_task_id=8')
assert.equal(f.mobileQrRoute('/incoming.html', 'http://localhost:18748', 'http://localhost:8002'), '/mobile/?mobile_page=incoming#incoming')
assert.equal(f.mobileQrRoute('/mobile/delivery-pick.html?task_id=88', 'http://localhost:18748', 'http://localhost:8002'), '/mobile/delivery-pick.html?task_id=88')
assert.equal(f.mobileQrRoute('/mobile/?task_id=8', 'http://localhost:18748', 'http://localhost:8002'), '/mobile/?mobile_page=production&task_id=8#production')
console.log('23 display-alias and QR contract checks passed')
